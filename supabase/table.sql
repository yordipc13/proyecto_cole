-- Ejecutar en Supabase SQL Editor. La migración conserva las solicitudes existentes.
create table if not exists public.solicitudes_estudiantes (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default timezone('utc'::text, now()),
    empresa text,
    actividad text,
    direccion text,
    contacto text,
    fecha text,
    telefono text,
    fax text,
    email text,
    puesto text,
    especialidades_requeridas text,
    modalidad text,
    entrevista text,
    horario text,
    vestimenta text,
    otro text,
    checks text
);

alter table public.solicitudes_estudiantes
    add column if not exists detalle_especialidades jsonb not null default '[]'::jsonb,
    add column if not exists estado text not null default 'recibida';

create table if not exists public.coordinadores (
    user_id uuid primary key references auth.users(id) on delete cascade,
    email text not null,
    created_at timestamptz not null default timezone('utc'::text, now())
);

create or replace function public.es_coordinador()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (
        select 1
        from public.coordinadores
        where user_id = auth.uid()
    );
$$;

revoke all on function public.es_coordinador() from public;
grant execute on function public.es_coordinador() to authenticated;

alter table public.solicitudes_estudiantes enable row level security;
alter table public.coordinadores enable row level security;

-- Remove permissive legacy policies so the policies below define the access boundary.
do $$
declare
    policy_record record;
begin
    for policy_record in
        select schemaname, tablename, policyname
        from pg_policies
        where schemaname = 'public'
          and tablename in ('solicitudes_estudiantes', 'coordinadores')
    loop
        execute format('drop policy %I on %I.%I', policy_record.policyname, policy_record.schemaname, policy_record.tablename);
    end loop;
end;
$$;

revoke all on table public.solicitudes_estudiantes from public, anon, authenticated;
revoke all on table public.coordinadores from public, anon, authenticated;
grant insert (
    empresa, actividad, direccion, contacto, fecha, telefono, fax, email, puesto,
    especialidades_requeridas, modalidad, entrevista, horario, vestimenta, otro,
    checks, detalle_especialidades
) on public.solicitudes_estudiantes to anon, authenticated;
grant select on public.solicitudes_estudiantes to authenticated;
grant update (estado) on public.solicitudes_estudiantes to authenticated;
grant select on public.coordinadores to authenticated;

do $$
declare
    identity_sequence text;
begin
    identity_sequence := pg_get_serial_sequence('public.solicitudes_estudiantes', 'id');
    if identity_sequence is not null then
        execute format('revoke all on sequence %s from public, anon, authenticated', identity_sequence);
        execute format('grant usage, select on sequence %s to anon, authenticated', identity_sequence);
    end if;
end;
$$;

create policy solicitudes_insert_public
    on public.solicitudes_estudiantes
    for insert to anon
    with check (
        modalidad = 'Práctica profesional'
        and jsonb_typeof(detalle_especialidades) = 'array'
        and jsonb_array_length(detalle_especialidades) > 0
    );

create policy solicitudes_insert_coordinacion
    on public.solicitudes_estudiantes
    for insert to authenticated
    with check (public.es_coordinador());

create policy solicitudes_select_coordinacion
    on public.solicitudes_estudiantes
    for select to authenticated
    using (public.es_coordinador());

create policy solicitudes_update_estado_coordinacion
    on public.solicitudes_estudiantes
    for update to authenticated
    using (public.es_coordinador())
    with check (public.es_coordinador());

create policy coordinadores_select_self
    on public.coordinadores
    for select to authenticated
    using (user_id = auth.uid());

